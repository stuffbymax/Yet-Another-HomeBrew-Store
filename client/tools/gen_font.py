#!/usr/bin/env python3
"""Generates common/font8x16.h (ASCII 32..126, 8x16, 1 bit/pixel, MSB = left) from a TTF.
Default font: DejaVu Sans Mono (free licence, see https://dejavu-fonts.github.io/License.html)."""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
size = int(sys.argv[2]) if len(sys.argv) > 2 else 13
font = ImageFont.truetype(ttf, size)
rows = []
for c in range(32, 127):
    im = Image.new("L", (8, 16), 0)
    ImageDraw.Draw(im).text((0, 12), chr(c), font=font, fill=255, anchor="ls")
    px = im.load()
    rows.append([sum((1 << (7 - x)) for x in range(8) if px[x, y] > 100) for y in range(16)])
out = ["/* GENERATED by tools/gen_font.py from DejaVu Sans Mono - do not edit. */",
       "#ifndef YAHBS_FONT8X16_H", "#define YAHBS_FONT8X16_H",
       "static const unsigned char font8x16[95][16] = {"]
for c, r in zip(range(32, 127), rows):
    out.append("  {" + ",".join(f"0x{b:02x}" for b in r) + f"}}, /* '{chr(c) if chr(c) not in '\\\\*/' else '?'}' */")
out += ["};", "#endif", ""]
open(sys.argv[3] if len(sys.argv) > 3 else "common/font8x16.h", "w").write("\n".join(out))
# preview
sheet = Image.new("L", (8 * 32 * 2, 16 * 3 * 2), 0)
for i, r in enumerate(rows):
    for y, b in enumerate(r):
        for x in range(8):
            if b >> (7 - x) & 1:
                for dx in (0, 1):
                    for dy in (0, 1):
                        sheet.putpixel((((i % 32) * 8 + x) * 2 + dx, ((i // 32) * 16 + y) * 2 + dy), 255)
sheet.save("/tmp/font_preview.png")
