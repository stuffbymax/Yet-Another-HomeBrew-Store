#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"
BUILD_ROOT="${BUILD_ROOT:-$PROJECT_ROOT/build}"

die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

require_command() {
  command -v "$1" >/dev/null 2>&1 || die "required command not found: $1"
}

clone_or_update() {
  local repository="$1"
  local destination="$2"
  if [[ -d "$destination/.git" ]]; then
    git -C "$destination" pull --ff-only
  elif [[ -e "$destination" ]]; then
    die "destination already exists and is not a Git repository: $destination"
  else
    mkdir -p "$(dirname -- "$destination")"
    git clone --depth 1 "$repository" "$destination"
  fi
}

write_toolchain_manifest() {
  local platform="$1"
  local toolchain_root="$2"
  local output_dir="$3"
  cat > "$output_dir/toolchain.env" <<EOF
# Generated by scripts/setup-$platform.sh. Do not commit this file.
PLATFORM=$platform
TOOLCHAIN_ROOT=$toolchain_root
EOF
}

prepare_build_dir() {
  local platform="$1"
  local toolchain_root="$2"
  local build_dir="$BUILD_ROOT/$platform"
  mkdir -p "$build_dir"
  write_toolchain_manifest "$platform" "$toolchain_root" "$build_dir"
  printf '%s\n' "$build_dir"
}
