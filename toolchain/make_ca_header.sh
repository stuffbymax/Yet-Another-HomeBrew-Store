#!/usr/bin/env bash
# Usage: make_ca_header.sh bundle.pem > client/common/ca_pem.h     (one or more certificates)
set -euo pipefail
[ -r "${1:-}" ] || { echo "usage: $0 bundle.pem" >&2; exit 1; }
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
awk -v d="$tmp" '/BEGIN CERTIFICATE/{n++} n{print > (d "/c" n ".pem")}' "$1"
ls "$tmp"/c*.pem >/dev/null 2>&1 || { echo "no certificates found in $1" >&2; exit 1; }
for f in "$tmp"/c*.pem; do openssl x509 -in "$f" -noout >/dev/null || { echo "invalid certificate in $1" >&2; exit 1; }; done
echo "/* generated by make_ca_header.sh */"
echo "static const char yahbs_ca_pem[] ="
for f in "$tmp"/c*.pem; do openssl x509 -in "$f" | sed 's/.*/  "&\\n"/'; done
echo ";"
